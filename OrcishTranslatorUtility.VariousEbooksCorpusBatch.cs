            }
            var nearKinOrdinal = 0;
            foreach (var line in VariousEbooksCorpusNearKinCandidateData.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
